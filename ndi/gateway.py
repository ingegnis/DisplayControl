"""NDI -> one FFmpeg encoder per source -> local fragmented MP4 for browsers.

No internet, shell commands, CDN, or paid application at runtime. ffmpeg and the
licensed NDI runtime must be installed separately. Test pattern is deliberately
labelled NON NDI. The web API never accepts executable paths or FFmpeg options.
"""
from __future__ import annotations
import hashlib
import json
import math
import os
from pathlib import Path
import re
import secrets
import shutil
import socket
import subprocess
import threading
import time
from .native import Runtime, Receiver, NDIError

PROFILES = {
    'light': {'label': 'Leggero / 640 x 360 / 15 fps', 'width': 640, 'height': 360, 'fps': 15, 'bitrate': '800k'},
    'standard': {'label': 'Standard / 1280 x 720 / 25 fps', 'width': 1280, 'height': 720, 'fps': 25, 'bitrate': '2200k'},
}
# Server-owned buffer policy; queue targets are not end-to-end latency.
PLAYBACK_MODES = {
    'responsive': {'mode': 'responsive', 'label': 'Reattiva / LAN',
                   'segmentSeconds': 0.5, 'targetBufferSeconds': 0.75,
                   'maxBufferSeconds': 1.8, 'pollMs': 100, 'initialSegments': 3,
                   'playlistSegments': 16},
    'stable': {'mode': 'stable', 'label': 'Stabile / piu buffer',
               'segmentSeconds': 1.0, 'targetBufferSeconds': 2.0,
               'maxBufferSeconds': 5.0, 'pollMs': 500, 'initialSegments': 3,
               'playlistSegments': 8},
}


def playback_policy(mode=None):
    value = mode if mode is not None else os.environ.get('CARISMA_LIVE_MODE', 'responsive')
    if value not in PLAYBACK_MODES:
        raise ValueError('CARISMA_LIVE_MODE deve essere responsive oppure stable.')
    return dict(PLAYBACK_MODES[value])


def keyframe_interval(profile, policy):
    # Round up to >= 0.5s at 15/25 fps; HLS targetduration >= 1.
    return max(1, math.ceil(PROFILES[profile]['fps'] * policy['segmentSeconds']))


SAFE_ID = re.compile(r'^[a-f0-9]{16}$')
SAFE_FILE = re.compile(r'^(init\.mp4|seg_[0-9]{9}\.m4s)$')


class GatewayError(RuntimeError):
    def __init__(self, message, status=400):
        super().__init__(message)
        self.status = status


def ffmpeg_binary(root: Path, explicit=''):
    candidates = [explicit, os.environ.get('CARISMA_FFMPEG', ''),
                  str(root / 'bin' / ('ffmpeg.exe' if os.name == 'nt' else 'ffmpeg')),
                  str(root / 'bin' / 'ffmpeg' / 'bin' / ('ffmpeg.exe' if os.name == 'nt' else 'ffmpeg')),
                  shutil.which('ffmpeg')]
    return next((str(Path(p).resolve()) for p in candidates if p and Path(p).is_file()), '')


def codec_string(init: bytes) -> str:
    """Read the H.264 decoder configuration record generated by our own encoder."""
    at = init.find(b'avcC')
    if at < 0 or at + 8 > len(init) or init[at + 4] != 1:
        raise GatewayError('Configurazione H.264 assente nel segmento iniziale.', 503)
    avc = init[at + 5:at + 8].hex().upper()
    return 'video/mp4; codecs="avc1.' + avc + ', mp4a.40.2"'


def parse_playlist(text: str):
    seq, duration, items = 0, 0.0, []
    for line in text.splitlines():
        line = line.strip()
        if line.startswith('#EXT-X-MEDIA-SEQUENCE:'):
            seq = int(line.split(':', 1)[1])
        elif line.startswith('#EXTINF:'):
            duration = float(line.split(':', 1)[1].split(',')[0])
        elif line and not line.startswith('#'):
            if not re.fullmatch(r'seg_[0-9]{9}\.m4s', line):
                raise GatewayError('Nome segmento non valido.', 503)
            items.append({'name': line, 'sequence': seq, 'duration': duration})
            seq += 1
    return items


class FeedSocket:
    """Loopback-only raw input for FFmpeg; works on Windows and Linux."""
    def __init__(self):
        self.listener = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        self.listener.bind(('127.0.0.1', 0))
        self.listener.listen(1)
        self.listener.settimeout(0.5)
        self.port = self.listener.getsockname()[1]
        self.client = None

    def accept(self, stop):
        while not stop.is_set():
            try:
                self.client, _ = self.listener.accept()
                self.client.settimeout(3)
                self.client.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
                return self.client
            except socket.timeout:
                pass
        return None

    def close(self):
        for s in (self.client, self.listener):
            if s:
                try:
                    s.shutdown(socket.SHUT_RDWR)
                except OSError:
                    pass
                try:
                    s.close()
                except OSError:
                    pass


class Stream:
    def __init__(self, manager, key, name, profile, test=False):
        self.manager, self.id = manager, key
        self.name, self.profile, self.test = name, profile, test
        self.playback = dict(manager.playback)
        self.stop_event = threading.Event()
        self.thread = threading.Thread(target=self.run, name='gateway-' + key, daemon=True)
        self.process = None
        self.generation = ''
        self.folder = None
        self.receiver = None
        self.last_frame_at = 0.0
        self.last_used = time.monotonic()
        self.started = time.time()
        self.stage = 'starting'
        self.error = ''
        self.restarts = 0
        self.total_frames = 0
        self.dropped_frames = 0
        self.input_format = ''
        self._stop_lock = threading.Lock()
        self._test_paused = False

    def touch(self):
        self.last_used = time.monotonic()

    def start(self):
        self.thread.start()
        return self

    def output_args(self):
        p = PROFILES[self.profile]
        gop = keyframe_interval(self.profile, self.playback)
        # Use fixed profiles; reject arbitrary HTTP encoder options.
        vf = ('scale={width}:{height}:force_original_aspect_ratio=decrease:force_divisible_by=2,'
              'pad={width}:{height}:(ow-iw)/2:(oh-ih)/2,setsar=1').format(**p)
        return ['-map', '0:v:0', '-map', '1:a:0', '-vf', vf,
                '-c:v', 'libx264', '-preset', 'ultrafast', '-tune', 'zerolatency',
                '-profile:v', 'baseline', '-level:v', '3.1', '-pix_fmt', 'yuv420p',
                '-r', str(p['fps']), '-g', str(gop), '-keyint_min', str(gop),
                '-sc_threshold', '0', '-bf', '0', '-b:v', p['bitrate'], '-threads', '2',
                '-c:a', 'aac', '-b:a', '128k', '-ar', '48000', '-ac', '2',
                '-f', 'hls', '-hls_time', str(self.playback['segmentSeconds']),
                '-hls_list_size', str(self.playback['playlistSegments']), '-hls_delete_threshold', '4',
                '-hls_segment_type', 'fmp4', '-hls_fmp4_init_filename', 'init.mp4',
                '-hls_flags', 'delete_segments+independent_segments+temp_file',
                '-hls_segment_filename', 'seg_%09d.m4s', 'stream.m3u8']

    def new_folder(self):
        parent = self.manager.live_dir / self.id
        parent.mkdir(parents=True, exist_ok=True)
        # Clean old generations before restart; reset clients.
        for entry in parent.iterdir():
            if entry.is_dir():
                shutil.rmtree(entry, ignore_errors=True)
        self.generation = secrets.token_hex(8)
        self.folder = parent / self.generation
        self.folder.mkdir()

    def spawn(self, inputs):
        self.new_folder()
        log = (self.folder / 'encoder.log').open('wb')
        flags = subprocess.CREATE_NO_WINDOW if os.name == 'nt' else 0
        try:
            self.process = subprocess.Popen(
                [self.manager.ffmpeg, '-hide_banner', '-nostdin', '-loglevel', 'warning', '-y']
                + inputs + self.output_args(), cwd=self.folder, stdin=subprocess.DEVNULL,
                stdout=subprocess.DEVNULL, stderr=log, creationflags=flags)
        finally:
            log.close()
        self.stage = 'buffering'

    def stop_process(self):
        proc = self.process
        if proc and proc.poll() is None:
            proc.terminate()
            try:
                proc.wait(timeout=3)
            except subprocess.TimeoutExpired:
                proc.kill()
                proc.wait(timeout=3)
        self.process = None

    def error_tail(self):
        try:
            return (self.folder / 'encoder.log').read_text(errors='replace')[-1000:]
        except (OSError, TypeError):
            return ''

    def run_test(self):
        p = PROFILES[self.profile]
        inputs = ['-re', '-f', 'lavfi', '-i', 'testsrc2=size={width}x{height}:rate={fps}'.format(**p),
                  '-re', '-f', 'lavfi', '-i', 'sine=frequency=440:sample_rate=48000', '-af', 'volume=0.04']
        self.input_format = 'TEST GENERATO / NON NDI'
        self.spawn(inputs)
        while not self.stop_event.wait(.2):
            if self.process.poll() is not None:
                raise GatewayError('FFmpeg si e arrestato: ' + self.error_tail(), 503)
            if not self._test_paused:
                self.last_frame_at = time.monotonic()
            self.stage = 'running' if self.manifest_exists() else 'buffering'

    def run_ndi(self):
        rx = Receiver(self.manager.runtime, self.name)
        self.receiver = rx
        feeds, threads = [], []
        iteration_stop = threading.Event()
        failure = []
        try:
            first = None
            self.stage = 'waiting'
            while not self.stop_event.wait(.04):
                first = rx.video()
                if first:
                    break
            if self.stop_event.is_set():
                return
            _, width, height, pix = first
            self.input_format = str(width) + ' x ' + str(height) + ' / ' + pix
            video_pipe, audio_pipe = FeedSocket(), FeedSocket()
            feeds = [video_pipe, audio_pipe]
            fps = PROFILES[self.profile]['fps']

            def video_feed():
                try:
                    conn = video_pipe.accept(iteration_stop)
                    if not conn:
                        return
                    index, origin = 0, time.monotonic()
                    while not iteration_stop.is_set():
                        frame = rx.video()
                        self.last_frame_at = rx.last_frame_at
                        self.total_frames, self.dropped_frames = rx.total_frames, rx.dropped_frames
                        if frame:
                            data, w, h, fmt = frame
                            if (w, h, fmt) != (width, height, pix):
                                raise NDIError('Formato sorgente cambiato: riavvio encoder.')
                            conn.sendall(data)
                        else:
                            conn.sendall(b'\0' * width * height * (2 if pix == 'uyvy422' else 4))
                        index += 1
                        delay = origin + index / fps - time.monotonic()
                        if delay < -1.5:
                            raise NDIError(f'Encoder video in ritardo ({index} frame, {time.monotonic()-origin:.2f}s, {self.stage}). Prova il profilo Leggero.')
                        iteration_stop.wait(max(0, delay))
                except (OSError, NDIError) as exc:
                    if not iteration_stop.is_set():
                        failure.append(str(exc))
                        iteration_stop.set()

            def audio_feed():
                try:
                    conn = audio_pipe.accept(iteration_stop)
                    if not conn:
                        return
                    index, origin = 0, time.monotonic()
                    while not iteration_stop.is_set():
                        conn.sendall(rx.audio(960))
                        index += 1
                        delay = origin + index * .02 - time.monotonic()
                        if delay < -1.5:
                            raise NDIError(f'Encoder audio in ritardo ({index} blocchi, {time.monotonic()-origin:.2f}s, {self.stage}): verificare carico CPU.')
                        iteration_stop.wait(max(0, delay))
                except (OSError, NDIError) as exc:
                    if not iteration_stop.is_set():
                        failure.append(str(exc))
                        iteration_stop.set()

            for fn in (video_feed, audio_feed):
                thread = threading.Thread(target=fn, daemon=True)
                threads.append(thread)
                thread.start()
            inputs = ['-thread_queue_size', '32', '-probesize', '32', '-analyzeduration', '0',
                      '-f', 'rawvideo', '-pixel_format', pix, '-video_size', f'{width}x{height}',
                      '-framerate', str(fps), '-i', f'tcp://127.0.0.1:{video_pipe.port}',
                      '-thread_queue_size', '128', '-probesize', '32', '-analyzeduration', '0',
                      '-f', 'f32le', '-ar', '48000', '-ac', '2',
                      '-i', f'tcp://127.0.0.1:{audio_pipe.port}']
            self.spawn(inputs)
            while not self.stop_event.wait(.2):
                if failure:
                    raise NDIError(failure[0])
                if self.process.poll() is not None:
                    raise GatewayError('FFmpeg si e arrestato: ' + self.error_tail(), 503)
                self.stage = 'running' if self.manifest_exists() else 'buffering'
        finally:
            iteration_stop.set()
            for feed in feeds:
                feed.close()
            self.stop_process()
            for thread in threads:
                thread.join(timeout=5)
            # Retain SDK state until capture threads stop.
            if not any(t.is_alive() for t in threads):
                rx.close()
            self.receiver = None

    def run(self):
        try:
            while not self.stop_event.is_set():
                self.error = ''
                try:
                    self.run_test() if self.test else self.run_ndi()
                except Exception as exc:
                    self.error = str(exc)[:1200]
                    self.stage = 'error'
                    self.restarts += 1
                finally:
                    self.stop_process()
                if self.stop_event.wait(min(30, 2 ** min(self.restarts, 4))):
                    break
        finally:
            self.stage = 'stopped'

    def manifest_exists(self):
        return bool(self.folder and (self.folder / 'stream.m3u8').is_file())

    def status(self):
        age = time.monotonic() - self.last_frame_at if self.last_frame_at else None
        file_age = None
        if self.manifest_exists():
            try:
                file_age = time.time() - (self.folder / 'stream.m3u8').stat().st_mtime
            except OSError:
                pass
        healthy = (self.stage == 'running' and age is not None and age < 3
                   and file_age is not None and file_age < 5)
        return {'id': self.id, 'sourceName': self.name, 'profile': self.profile,
                'test': self.test, 'generation': self.generation, 'stage': self.stage,
                'healthy': healthy, 'frameAge': round(age, 2) if age is not None else None,
                'manifestAge': round(file_age, 2) if file_age is not None else None,
                'frames': self.total_frames, 'droppedFrames': self.dropped_frames,
                'inputFormat': self.input_format, 'error': self.error,
                'restarts': self.restarts, 'startedAt': self.started,
                'playback': dict(self.playback),
                'segmentNominalSeconds': keyframe_interval(self.profile, self.playback) / PROFILES[self.profile]['fps']}

    def manifest(self):
        self.touch()
        status = self.status()
        if not self.manifest_exists():
            return {**status, 'ready': False, 'segments': []}
        try:
            folder, generation = self.folder, self.generation
            items = parse_playlist((folder / 'stream.m3u8').read_text())
            mime = codec_string((folder / 'init.mp4').read_bytes())
            base = f'/api/ndi/media/{self.id}/{generation}/'
            for item in items:
                item['url'] = base + item['name']
            return {**status, 'generation': generation, 'ready': len(items) >= 2,
                    'mime': mime, 'init': base + 'init.mp4', 'segments': items}
        except (OSError, ValueError, GatewayError):
            return {**status, 'ready': False, 'segments': []}

    def stop(self):
        with self._stop_lock:
            self.stop_event.set()
            self.stop_process()
            if self.thread.is_alive() and threading.current_thread() is not self.thread:
                self.thread.join(timeout=8)


class Gateway:
    def __init__(self, root: Path, data_dir: Path, library='', ffmpeg='', extra_ips='', max_streams=2, live_mode=None):
        self.playback = playback_policy(live_mode)
        self.root = Path(root)
        self.live_dir = Path(data_dir) / 'live'
        self.live_dir.mkdir(exist_ok=True, parents=True)
        # Temporary encoder output only; uploaded assets stay separate.
        for item in self.live_dir.iterdir():
            if item.is_dir() and SAFE_ID.fullmatch(item.name):
                shutil.rmtree(item, ignore_errors=True)
        self.runtime = Runtime(root, library, extra_ips)
        self.ffmpeg = ffmpeg_binary(root, ffmpeg)
        self.max_streams = max(1, min(8, max_streams))
        self.streams = {}
        self.lock = threading.RLock()
        self.closed = threading.Event()
        self.ffmpeg_ok = False
        self.ffmpeg_error = ''
        self._check_ffmpeg()
        self.reaper = threading.Thread(target=self._reap, daemon=True, name='gateway-reaper')
        self.reaper.start()

    def _check_ffmpeg(self):
        if not self.ffmpeg:
            self.ffmpeg_error = 'FFmpeg non trovato: installalo o usa bin/ffmpeg.exe o CARISMA_FFMPEG.'
            return
        try:
            result = subprocess.run([self.ffmpeg, '-hide_banner', '-encoders'],
                                    capture_output=True, timeout=10, text=True)
            self.ffmpeg_ok = result.returncode == 0 and 'libx264' in result.stdout and ' aac ' in result.stdout
            if not self.ffmpeg_ok:
                self.ffmpeg_error = 'Serve una build FFmpeg con encoder libx264 e AAC.'
        except (OSError, subprocess.TimeoutExpired) as exc:
            self.ffmpeg_error = 'FFmpeg non utilizzabile: ' + str(exc)

    def status(self):
        with self.lock:
            streams = [s.status() for s in self.streams.values()]
        return {'runtime': self.runtime.status(),
                'ffmpeg': {'available': self.ffmpeg_ok, 'error': self.ffmpeg_error},
                'profiles': PROFILES, 'streams': streams, 'maxStreams': self.max_streams,
                'transport': 'H264-AAC-fMP4-local', 'offlineInternet': True,
                'playback': dict(self.playback),
                'note': 'Test pattern non NDI. Latenza con buffering, non adatto a sincronismo videowall.'}

    def sources(self):
        try:
            return {'sources': self.runtime.sources(), 'error': ''}
        except NDIError as exc:
            return {'sources': [], 'error': str(exc)}

    def start(self, body):
        if not isinstance(body, dict):
            raise GatewayError('Richiesta non valida.')
        test = body.get('test') is True
        name = 'TEST LOCALE / NON NDI' if test else body.get('sourceName', '')
        profile = body.get('profile', 'light')
        if not isinstance(name, str) or not name.strip() or len(name) > 300 or '\0' in name:
            raise GatewayError('Inserisci il nome esatto della sorgente NDI.')
        if profile not in PROFILES:
            raise GatewayError('Profilo non valido.')
        name = name.strip()
        if not self.ffmpeg_ok:
            raise GatewayError(self.ffmpeg_error, 503)
        if not test:
            try:
                self.runtime.load()
            except NDIError as exc:
                raise GatewayError(str(exc), 503) from exc
        key = hashlib.sha256(json.dumps([name, profile, test]).encode()).hexdigest()[:16]
        with self.lock:
            existing = self.streams.get(key)
            if existing:
                existing.touch()
                return existing.status()
            if len(self.streams) >= self.max_streams:
                raise GatewayError('Limite sorgenti simultanee raggiunto. Arresta un gateway inutilizzato.', 409)
            stream = Stream(self, key, name, profile, test)
            self.streams[key] = stream
            stream.start()
            return stream.status()

    def get(self, key):
        with self.lock:
            stream = self.streams.get(key)
        if stream is None:
            raise GatewayError('Gateway non attivo. Ricollega il player.', 404)
        return stream

    def stop(self, key):
        with self.lock:
            stream = self.streams.pop(key, None)
        if stream:
            stream.stop()
            shutil.rmtree(self.live_dir / key, ignore_errors=True)
        return {'ok': True}

    def media(self, key, generation, filename):
        if not SAFE_ID.fullmatch(key) or not SAFE_ID.fullmatch(generation) or not SAFE_FILE.fullmatch(filename):
            raise GatewayError('Percorso media non valido.', 400)
        stream = self.get(key)
        stream.touch()
        if generation != stream.generation:
            raise GatewayError('Il gateway e stato riavviato. Ricaricare il manifest.', 409)
        path = self.live_dir / key / generation / filename
        try:
            return path.read_bytes()
        except OSError as exc:
            raise GatewayError('Segmento non disponibile.', 404) from exc

    def _reap(self):
        while not self.closed.wait(10):
            with self.lock:
                keys = [s.id for s in self.streams.values() if time.monotonic() - s.last_used > 60]
            for key in keys:
                self.stop(key)

    def close(self):
        self.closed.set()
        with self.lock:
            keys = list(self.streams)
        for key in keys:
            self.stop(key)
        self.reaper.join(timeout=2)
        self.runtime.close()
